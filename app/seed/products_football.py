from app.seed.constants import rand
from app.seed.model import ProductSpec, V, VariantSpec

F = "FBL"
SIZES = ("S", "M", "L", "XL")


def _sizes(price: int, stock: int = 12, sizes: tuple[str, ...] = SIZES) -> tuple[VariantSpec, ...]:
    return tuple(V(price, stock + i, size=s) for i, s in enumerate(sizes))


def _shirt(
    code: str,
    sub: str,
    slug: str,
    name: str,
    brand: str,
    desc: str,
    price: int,
    *,
    fixture: str | None = None,
    featured: bool = False,
    season: str = "2025/26",
) -> ProductSpec:
    return ProductSpec(
        code,
        sub,
        slug,
        name,
        brand,
        desc,
        (
            ("Season", season),
            ("Material", "Recycled polyester"),
            ("Fit", "Regular"),
            ("Listing", "Fictional / unofficial demo replica"),
        ),
        _sizes(price),
        featured=featured,
        fixture=fixture,
    )


