from app.seed.constants import rand
from app.seed.model import ProductSpec, V, VariantSpec

H = "SHO"


def _sizes(
    price: int,
    colour: str,
    sizes: tuple[str, ...] = ("UK 7", "UK 8", "UK 9", "UK 10"),
    stock: int = 9,
) -> tuple[VariantSpec, ...]:
    return tuple(V(price, stock + i, colour=colour, size=s) for i, s in enumerate(sizes))


def _shoe(
    code: str,
    sub: str,
    slug: str,
    name: str,
    brand: str,
    desc: str,
    price: int,
    colour: str,
    *,
    featured: bool = False,
    kind: str = "Road",
) -> ProductSpec:
    return ProductSpec(
        code,
        sub,
        slug,
        name,
        brand,
        desc,
        (("Type", kind), ("Upper", "Engineered mesh"), ("Sole", "Rubber")),
        _sizes(price, colour),
        featured=featured,
    )


